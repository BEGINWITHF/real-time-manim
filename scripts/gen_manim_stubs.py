#!/usr/bin/env python3
"""Generate ``manim-stubs/`` for the ManimCE copy bundled in RTM.

``real_time_manim/manim/`` is upstream ManimCE's source tree, renamed.  Its
modules import each other as ``from manim.constants import ...`` -- the name
RTM installs into ``sys.modules`` at import time.  That works at runtime, but a
static analyzer never executes ``_install_bundled_manim()``, so every one of
those imports is unresolved for Pylance/pyright/mypy.  The result is that
``from real_time_manim import *`` exports untyped names and inherited methods
(``Square.set_fill``, ``Create.__init__``, ...) come out as ``Unknown``.

A PEP 561 stub-only package fixes this without touching the vendored code:
pyright resolves ``import manim`` to ``manim-stubs/``, and each stub re-exports
the real module by its on-disk path.  Nothing is added to ``sys.path`` and
nothing changes at runtime -- the directory name has a hyphen, so Python
cannot import it.

Run from the repository root::

    python scripts/gen_manim_stubs.py
"""

from __future__ import annotations

import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "real_time_manim"
STUBS = ROOT / "manim-stubs"

IMPORT_RE = re.compile(r"^\s*(?:from|import)\s+(manim(?:\.\w+)*)", re.MULTILINE)

HEADER = (
    "# Generated by scripts/gen_manim_stubs.py -- do not edit.\n"
    "# Type-only re-export of the ManimCE copy bundled in real_time_manim.\n"
)


def imported_modules() -> list[str]:
    """Every ``manim[.x]`` module imported anywhere in the package."""
    found: set[str] = set()
    for path in PACKAGE.rglob("*.py"):
        found.update(IMPORT_RE.findall(path.read_text(encoding="utf-8", errors="ignore")))
    return sorted(found - {"manim"})


def main() -> None:
    if STUBS.exists():
        shutil.rmtree(STUBS)
    STUBS.mkdir(parents=True)

    (STUBS / "py.typed").write_text("", encoding="utf-8")
    (STUBS / "__init__.pyi").write_text(
        HEADER + "from real_time_manim.manim import *\n", encoding="utf-8"
    )

    modules = imported_modules()
    for module in modules:
        target = STUBS.joinpath(*module.split(".")[1:]).with_suffix(".pyi")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(
            HEADER + f"from real_time_manim.{module} import *\n", encoding="utf-8"
        )

    print(f"wrote {len(modules) + 1} stub modules to {STUBS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
